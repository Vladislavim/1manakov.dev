export function guideIndexMetadata(topic?: string, page = 1) {
  const title = topic ? guideTopics[topic] || 'Практика дизайна' : 'Практика дизайна интерфейсов';
  const description = topic ? descriptions[topic] || title : 'Прикладные разборы форм, навигации, доступности и структуры сайта с примерами и проверками.';
  const base = topic ? `/guides/topic/${topic}` : '/guides';
  return pageMetadata({ title: page > 1 ? `${title}: страница ${page}` : title,
    description: page > 1 ? `Страница ${page}. ${description}` : description,
    path: page > 1 ? `${base}/page/${page}` : base, locale: 'ru_RU' });
}
